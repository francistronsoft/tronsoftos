import test from 'node:test';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { createRequire } from 'node:module';
import { mkdtempSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes, scryptSync } from 'node:crypto';
const { bootstrapBi } = createRequire(import.meta.url)('../../scripts/bootstrap-tron-bi-user.cjs');
test('BI initializes empty users once and preserves accounts, API keys and business data', () => {
  const dir = mkdtempSync(join(tmpdir(), 'bi-bootstrap-'));
  const dbPath = join(dir, 'bi.db'), seedPath = join(dir, 'seed.json');
  const salt = randomBytes(16), password = randomBytes(20).toString('hex');
  const passwordHash = `scrypt$16384$8$1$${salt.toString('hex')}$${scryptSync(password, salt, 32).toString('hex')}`;
  writeFileSync(seedPath, JSON.stringify({ username: 'tronsoft', passwordHash }));
  const run = () => bootstrapBi({ Database: DatabaseSync, dbPath, seedPath });
  try {
    assert.equal(run(), 'created');
    let db = new DatabaseSync(dbPath);
    assert.equal(db.prepare('SELECT MD5_SENHA FROM USUARIO').get().MD5_SENHA, passwordHash);
    db.exec("UPDATE USUARIO SET MD5_SENHA='changed'; CREATE TABLE API_KEY (HASH TEXT); INSERT INTO API_KEY VALUES ('preserve'); CREATE TABLE VENDA(ID INTEGER); INSERT INTO VENDA VALUES (42)");
    db.close();
    assert.equal(run(), 'preserved');
    db = new DatabaseSync(dbPath);
    assert.equal(db.prepare('SELECT MD5_SENHA FROM USUARIO').get().MD5_SENHA, 'changed');
    db.exec("DELETE FROM USUARIO; INSERT INTO USUARIO VALUES ('other','keep')"); db.close();
    assert.equal(run(), 'preserved');
    db = new DatabaseSync(dbPath);
    assert.equal(db.prepare('SELECT COUNT(*) n FROM USUARIO').get().n, 1);
    db.exec('DELETE FROM USUARIO'); db.close();
    assert.equal(run(), 'created');
    db = new DatabaseSync(dbPath);
    assert.equal(db.prepare('SELECT HASH FROM API_KEY').get().HASH, 'preserve');
    assert.equal(db.prepare('SELECT ID FROM VENDA').get().ID, 42); db.close();
    assert.equal(bootstrapBi({ enabled: false, dbPath: join(dir, 'disabled.db') }), 'disabled');
    assert.equal(existsSync(join(dir, 'disabled.db')), false);
    writeFileSync(seedPath, '{}');
    assert.throws(() => bootstrapBi({ Database: DatabaseSync, dbPath: join(dir, 'invalid.db'), seedPath }), /Invalid/);
    db = new DatabaseSync(join(dir, 'invalid.db'));
    assert.equal(db.prepare("SELECT COUNT(*) n FROM sqlite_master WHERE name='USUARIO'").get().n, 0); db.close();
  } finally { rmSync(dir, { recursive: true, force: true }); }
});
